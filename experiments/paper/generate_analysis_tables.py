"""Generate aggregate-only TeX inclusions from the ICE v2 analysis reports."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT/'experiments/paper/generated'
DEST.mkdir(exist_ok=True)
ab = json.loads((ROOT/'experiments/flaw_ablation/buildup/results/exp3_bootstrap_report.json').read_text())
lines = ['% Generated by experiments/paper/generate_analysis_tables.py; do not edit.']
for macro, step in [('Lexical','add_bm25'),('Fusion','add_rrf')]:
    d = ab['step_deltas'][step]
    lines += [rf'\newcommand{{\{macro}Delta}}{{{d["point"]:+.2f}}}',
              rf'\newcommand{{\{macro}CI}}{{[{d["ci"][0]:+.2f},{d["ci"][1]:+.2f}]}}']
for macro,key in [('FusionBare','rrf_vs_bare (add_rrf - bare_vector)'),('FullBare','full_ice_vs_bare (full_ice - bare_vector)'),('FullVector','full_ice_vs_vecbaseline (full_ice - vector_baseline)')]:
    d=ab['headline_contrasts'][key]
    lines += [rf'\newcommand{{\{macro}CI}}{{[{d["ci"][0]:+.2f},{d["ci"][1]:+.2f}]}}']
(DEST/'ablation_macros.tex').write_text('\n'.join(lines)+'\n')
r=json.loads((ROOT/'experiments/mature/results/scoring_sensitivity.json').read_text())['views']
lines=[r'\begin{tabular}{llrrr}',r'\toprule',r'Scoring & Regime & $n$ & $\Delta$ & Probe-cluster 95\% CI \\',r'\midrule']
for name,label in [('merged_historical','Merged, archived'),('automated_only_historical','Automated, archived'),('merged_complete','Merged, complete'),('automated_only_complete','Automated, complete')]:
    for regime in ('all','ordinary','density'):
        v=r[f'{name}_{regime}'];d=v['mean_difference']
        lines.append(f'{label} & {regime.capitalize()} & {v["n"]:,} & ${d["delta"]:+.3f}$ & $[{d["ci95"][0]:+.3f},{d["ci95"][1]:+.3f}]$ '+r'\\')
lines.extend([r'\bottomrule',r'\end{tabular}'])
(DEST/'scoring_sensitivity.tex').write_text('\n'.join(lines)+'\n')
