#!/usr/bin/env python3
"""Create the isolated v2 schema for the LongMemEval run.

⚑ RUN FROM THE WORKTREE:
    cd /home/deepnar/Programs/ice-worktrees/v2-paper-eval
    uv run python /home/deepnar/Programs/ice/experiments/lme/setup_v2_db.py

WHY NOT `alembic upgrade head`
------------------------------
Two reasons, both found the hard way.

1. **alembic/env.py reads the database URL ONLY from alembic.ini** -- it ignores
   `.env` and `Settings`. At the tag that file hardcodes `ice_db`, the LIVE store.
   Running `alembic upgrade head` in the worktree therefore connects to the real
   database. It did: it read main's head `a1c4e7b90d22`, which does not exist among
   the tag's 12 migrations, and failed at revision lookup before changing anything.
   The worktree's alembic.ini is now repointed at `ice_lme_v2` so that cannot recur.

2. **The tag's migration chain cannot build the schema from an empty database.**
   It was only ever applied to an evolving dev DB. Two independent failures:
   `15998d67a6f2` (autogenerated -- TRAPS #14) drops three HNSW indexes the base
   chain never creates, and a later migration alters `review_queue`, a table no
   migration creates. These are not one-line fixes; the chain assumes state it does
   not build.

So the schema comes from `Base.metadata`, which CLAUDE.md holds authoritative
anyway ("where any doc conflicts with code, code wins"). alembic is then STAMPED to
head so later tooling sees a consistent version, without replaying the broken chain.

⚑ The end state deliberately has **no HNSW vector index**. That is not an omission:
`15998d67a6f2` drops all three in `upgrade()` and nothing recreates them, so the
paper's own database had none either. Vector search is exact cosine, not ANN --
which is also deterministic, and therefore better for a benchmark.
"""

from __future__ import annotations

import os
import sys

# This file lives on `main` but must import `src.*` from the WORKTREE we are run
# from. Python seeds sys.path with the script's directory, not the cwd, so the
# worktree root goes on explicitly -- the same thing tests/ does.
sys.path.insert(0, os.getcwd())

EXPECTED_DB = "ice_lme_v2"


def main() -> int:
    from sqlalchemy import create_engine, inspect, text

    from src.api.config import settings
    from src.memory.models import Base

    url = settings.database_url
    if EXPECTED_DB not in url:
        print(f"⛔ REFUSING TO RUN.\n"
              f"   database_url does not name '{EXPECTED_DB}': {url.rsplit('@', 1)[-1]}\n"
              f"   This script calls create_all(); pointing it at the live store is\n"
              f"   not something to do by accident. Check the worktree's .env.",
              file=sys.stderr)
        return 2

    engine = create_engine(url)
    with engine.connect() as conn:
        conn.execute(text("CREATE EXTENSION IF NOT EXISTS vector"))
        conn.commit()

    Base.metadata.create_all(engine)

    tables = sorted(inspect(engine).get_table_names())
    print(f"created {len(tables)} tables in {EXPECTED_DB}")

    # Verify the dimension the whole run depends on. v2 stores Vector(384); main
    # stores 1024 with the same model name, and nothing else would flag the mix.
    with engine.connect() as conn:
        dim = conn.execute(text("""
            SELECT a.atttypmod FROM pg_attribute a
            JOIN pg_class c ON c.oid = a.attrelid
            WHERE c.relname = 'episodic_memory' AND a.attname = 'embedding'
        """)).scalar()
    print(f"episodic_memory.embedding dimension: {dim}")
    if dim != 384:
        print(f"⛔ expected 384, got {dim}. This is not the v2 schema.", file=sys.stderr)
        return 3

    # Stamp alembic to head WITHOUT replaying the chain, so future tooling in this
    # worktree sees a coherent version rather than an empty alembic_version table.
    try:
        from alembic import command
        from alembic.config import Config
        cfg = Config("alembic.ini")
        command.stamp(cfg, "head")
        print("alembic stamped to head (chain not replayed -- see module docstring)")
    except Exception as exc:  # noqa: BLE001 -- stamping is convenience, not correctness
        print(f"note: alembic stamp skipped ({type(exc).__name__}: {exc})")

    print("\nready. next:")
    print("  ./experiments/lme/run_lme.sh oracle --plan")
    return 0


if __name__ == "__main__":
    sys.exit(main())
